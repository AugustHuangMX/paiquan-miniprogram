/**
 * 广告位配置。
 *
 * 现状：**已开通流量主并配置了广告位**（三个页面共用同一个原生模板广告位）。
 * 想分开看每页数据的话，去后台建 3 个，把 ID 分别填到下面三行即可。
 *
 * 为什么要有这一层开关：
 *   广告组件的 unit-id 为空或格式不对，会报错或渲染成一块空白 ——
 *   所以这里做一层校验：ID 不合法就当没配，页面上什么都不出现。
 *
 * 开通之后怎么用：
 *   1. 小程序后台 → 流量主 → 广告位管理 → 新建广告位 → 类型选
 *      **「原生模板广告」**，模板选 **「横幅」**（Banner 广告已于 2024-08
 *      由系统自动升级为原生模板广告，后台里已经没有 Banner 这个选项了），
 *      拿到形如 adunit-1a2b3c4d5e6f7788 的 ID
 *   2. 填到下面 AD_UNITS 里对应的页面（三页共用一个 ID 也行，分开建便于看数据）
 *   3. 重新上传代码即可，**不用改任何页面逻辑**
 *
 * 关于组件：现在用 <ad>。按文档，原生模板广告对应的是 <ad-custom>；
 * 但换成 <ad-custom> 那次正好赶上开发者工具资源耗尽而白屏
 * （控制台是 ERR_INSUFFICIENT_RESOURCES，跟组件无关，重启就好了），
 * 所以先保守用 <ad>。后台那一行的「获取代码」会给官方写法，以它为准。
 *
 * 关于位置：**要放在用户看得到的地方，否则等于没投**。
 * 流量主的收入来自曝光和点击，一直滚不到的广告是 0 收益。
 * 但也不能为了曝光违规 —— 微信禁止遮挡内容、诱导点击、把广告压在按钮上。
 * 所以现在的放法是「**两段内容之间**的自然分隔处」：
 *   排位专区 = 分数线卡片下面；比赛 = 赛事名次那一段下面；
 *   地图 = 页脚上方（那一页四行要占满一屏，是用户明确要求的一进来看不到广告）。
 */
var AD_UNITS = {
  // 四个页面**共用同一个广告位 ID**（后台只建了一个）。想分开看每页数据的话，
  // 去后台各建一个、把 ID 分别填到下面四行即可，页面代码不用改。
  // 2026-10-12 换位：旧位是「卡片式」模板（16:9，很高），第一屏塞不下 →
  // 广告只露一条边，基本不计曝光。新位用较扁的模板。
  // 2026-10-16 用户决定：地图页也放广告（位置在四张模式卡之后、页脚之前，
  // 不影响"第一屏四行占满"那条）。
  maps: "adunit-419d525ab9b59819",
  predator: "adunit-419d525ab9b59819",
  // ⚠️ 2026-10-16 修：这里原来叫 stats（战绩页）。战绩页已经删了，
  //    而比赛页的 WXML 里一直有个 adbox + `adUnitFor("matches")` ——
  //    键名对不上 → **那个广告位从来没生效过**（永远拿到空串，组件不渲染）。
  //    现在把键名改成 matches，比赛页的广告才真的会出现。
  matches: "adunit-419d525ab9b59819",
  // 猜圈页：**只在本局结束时**才出现（玩的时候不挡地图、不贴按钮）。
  ringguessr: "adunit-419d525ab9b59819"
};

var VALID = /^adunit-[0-9a-z]+$/i;

/**
 * @param {string} page 页面名：maps / predator / matches / ringguessr
 * @returns {string} 合法的广告位 ID；没配或格式不对则返回空串
 */
function adUnitFor(page) {
  if (!page || !Object.prototype.hasOwnProperty.call(AD_UNITS, page)) return "";
  var id = String(AD_UNITS[page] == null ? "" : AD_UNITS[page]).trim();
  return VALID.test(id) ? id : "";
}

module.exports = {
  AD_UNITS: AD_UNITS,
  adUnitFor: adUnitFor
};
